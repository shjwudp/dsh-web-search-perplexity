/**
 * Guard the embedded runtime skill against the failure mode this plugin shipped
 * once: `skills.register()` in `@deepseek-ai/dsh-skill` validates only
 * name/description/invocation, so a definition without `source` registers
 * silently and is listed normally — and only throws later, when it is loaded:
 *
 *   loaded skill "perplexity-research" source must be a string
 *
 * This gate replays both halves of that split for the exact object the plugin
 * hands to `skills.register()`:
 *
 *   - the registration path (`validateRuntimeSkill()`), which is the half that
 *     says "fine" and therefore cannot be trusted to catch the defect;
 *   - the load path (`validateDefinition()`, after the registry's
 *     `invocation`/`provider` defaults are applied), which is the half that
 *     throws at `get()` time.
 *
 * It also re-renders `src/skill.js` in memory and compares it with the file on
 * disk, so a stale or hand-edited generated artifact cannot pass by predating a
 * regression in the generator.
 *
 * Run with: npm run check:skill
 */

import { readFileSync } from 'node:fs'

import { PERPLEXITY_RESEARCH_SKILL as skill } from '../src/skill.js'
import { renderSkillModule } from './build-skill.mjs'

const SKILL_NAME = /^[a-z0-9]+(?:-[a-z0-9]+)*$/

const isNonEmptyString = (value) => typeof value === 'string' && value.length > 0
const isOptionalString = (value) => value === undefined || typeof value === 'string'
const isInvocationPolicy = (value) =>
  value === undefined ||
  (typeof value === 'object' &&
    value !== null &&
    !Array.isArray(value) &&
    typeof value.modelInvocable === 'boolean' &&
    typeof value.userInvocable === 'boolean')

// Registration path: dsh-skill validateRuntimeSkill(). Note what is absent:
// `source` is not looked at here, which is why the defect registered silently.
const registrationChecks = [
  ['name is a kebab-case string', typeof skill.name === 'string' && SKILL_NAME.test(skill.name)],
  ['description is a non-empty string', isNonEmptyString(skill.description)],
  ['invocation is an optional { modelInvocable, userInvocable } boolean policy', isInvocationPolicy(skill.invocation)],
]

// Load path: the registry stores the definition with defaults applied and later
// re-validates it with validateDefinition().
const definition = {
  ...skill,
  invocation: skill.invocation ?? { modelInvocable: true, userInvocable: true },
  provider: skill.provider ?? 'runtime',
}
const loadChecks = [
  ['name is a kebab-case string', typeof definition.name === 'string' && SKILL_NAME.test(definition.name)],
  ['description is a non-empty string', isNonEmptyString(definition.description)],
  ['invocation is an optional { modelInvocable, userInvocable } boolean policy', isInvocationPolicy(definition.invocation)],
  ['whenToUse is an optional string', isOptionalString(definition.whenToUse)],
  ['source is a non-empty string (required at load time)', isNonEmptyString(definition.source)],
  ['provider is a string', typeof definition.provider === 'string'],
  ['content is a non-empty string', isNonEmptyString(definition.content)],
  ['path is an optional string', isOptionalString(definition.path)],
]

// `src/skill.js` is generated by scripts/build-skill.mjs; never hand-edited.
// CRLF is normalized away so a Windows working tree (core.autocrlf=true) is not
// reported as stale when only the line endings differ.
const normalize = (text) => text.replace(/\r\n/g, '\n')
const artifact = normalize(readFileSync(new URL('../src/skill.js', import.meta.url), 'utf8'))
const { file: expected } = renderSkillModule()
const freshnessChecks = [
  ['src/skill.js is current (run `npm run build:skill`)', artifact === normalize(expected)],
]

const failures = [...registrationChecks, ...loadChecks, ...freshnessChecks].filter(([, ok]) => !ok)

if (failures.length > 0) {
  for (const [label] of failures) console.error(`FAIL: ${label}`)
  console.error(`\n${failures.length} skill check(s) failed — loading "skill ${skill.name}" would throw.`)
  process.exit(1)
}

console.log(`ok: skill "${skill.name}" (source: ${definition.source}, ${definition.content.length} chars)`)
